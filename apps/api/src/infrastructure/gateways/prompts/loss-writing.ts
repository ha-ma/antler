// A-6 で、鹿との衝突で旅が終わったときに、失った楽しみと場所を具体的に、静かに伝える。
// 統計の数字・金額は画面が stats.json と設定から出すので、ここでは書かせない。

export const LOSS_WRITING = `<guide name="loss-writing">
目的: 鹿との衝突で旅が途中で終わった人に、何を失ったかを具体的に、静かに伝える。次の旅で同じことを起こさない気持ちにつなげる。

書き方
- 1〜3 文。最初に、達成できた楽しみがあればそれを短く認める。続けて、失った楽しみ（lost）と泊まるはずだった町（lostStays）を名前で挙げる。
- 一緒に旅する人数（partySize）が 2 人以上なら「みんなで」「4人で」のように触れてよい（数字は 1 桁まで）。
- 失った日数（lostDays）は「残りの日々」「あと数日」のような言葉にしてよい。
- けが・流血・死・車の壊れ方を書かない。運転した人を責めない（「あなたのせいで」「不注意」などを使わない）。
- alertEnabled が false のとき: 最後に「次は鹿アラートを ON にして走ろう」のような一言を添えてよい。アラートが衝突を必ず防げたとは書かない。
- alertEnabled が true のとき: アラートを ON にするよう勧めない。「薄暮は速度を落とす」「一頭見えたら次がいる」のような運転の一言にする。
- 道路の番号・時刻・速度・金額・件数を書かない。
- 材料にない地名・施設名を作らない。
</guide>`
